"""Parallel model benchmark for a bot folder.

This is deliberately separate from the submission leaderboard.  The bot and its
prompt stay fixed while one or more model ids vary.  Each worker owns a browser
and an asset server because Playwright's synchronous API cannot be shared.
"""

from __future__ import annotations

import hashlib
import json
import multiprocessing as mp
import os
import statistics
from datetime import datetime, timezone
from pathlib import Path
from tempfile import TemporaryDirectory
import time
from typing import Any, Callable

from .bench import STANDARD_SEEDS

ROOT = Path(__file__).resolve().parents[2]
BOTS = ROOT / "bots"
OUT = ROOT / "llm-bench" / "cartographer"
README = OUT / "README.md"
README_BEGIN = "<!-- BEGIN cartographer-standings: generated by `pokelike llm-bench --table`, do not edit -->"
README_END = "<!-- END cartographer-standings -->"


def slug(model: str) -> str:
    return model.replace("/", "--").replace(":", "-").replace(" ", "-")


def bot_path(name: str) -> Path:
    path = Path(name)
    if "/" not in name and "\\" not in name:
        path = BOTS / name
    path = path if path.name == "bot.py" else path / "bot.py"
    if not path.is_file():
        raise FileNotFoundError(f"no bot.py at {path}")
    return path


def fingerprint(name: str) -> dict[str, str]:
    paths = [bot_path(name), ROOT / "src/pokelike/bot/llm.py",
             ROOT / "src/pokelike/core/render.py", ROOT / "src/pokelike/core/bridge.js"]
    h = hashlib.sha256()
    for path in paths:
        h.update(str(path.relative_to(ROOT)).encode())
        h.update(path.read_bytes())
    return {"sha256": h.hexdigest()[:16], "files": ",".join(str(p.relative_to(ROOT)) for p in paths)}


def _worker(bot_name: str, model: str, seeds: list[int], endpoint: str | None,
            token: str | None, port: int, site: str, max_steps: int,
            result_path: str, error_path: str) -> None:
    from .assets.server import AssetServer
    from .bot.catalogue import load_class
    from .core.game import Game
    from .runner import play_run

    cls = load_class(bot_path(bot_name))
    bot = cls(seed=0, model=model, endpoint=endpoint, token=token)
    server = AssetServer(Path(site), port=port)
    server.start()
    game = Game(url=server.url)
    game.open()
    try:
        for seed in seeds:
            full = play_run(game, bot, seed, max_steps=max_steps)
            notes = bot.notes()
            row = {
                "seed": seed,
                "steps": full["steps"],
                "score": full["score"],
                "badges": full["badges"],
                "maps": full["maps"],
                "kos": full["kos"],
                "faints": full["faints"],
                "ending": full["ending"],
                "stalled": full["stalled"],
                "tokens_in": notes.get("tokens_in", 0),
                "tokens_out": notes.get("tokens_out", 0),
                "cached_tokens": notes.get("cached_tokens", 0),
                "cache_write_tokens": notes.get("cache_write_tokens", 0),
                "reasoning_tokens": notes.get("reasoning_tokens", 0),
                "cost": notes.get("cost"),
                "fallbacks": notes.get("fallbacks", 0),
                "turns": notes.get("turns", 0),
                "calls": notes.get("calls", 0),
            }
            with Path(result_path).open("a", encoding="utf-8") as out:
                out.write(json.dumps(row, separators=(",", ":")) + "\n")
                out.flush()
                os.fsync(out.fileno())
    except BaseException as exc:
        Path(error_path).write_text(
            f"{type(exc).__name__}: {exc}\n", encoding="utf-8"
        )
        raise
    finally:
        game.close()
        server.stop()


def _read_worker_rows(paths: list[Path]) -> list[dict[str, Any]]:
    rows = []
    for path in paths:
        if not path.is_file():
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            if line:
                rows.append(json.loads(line))
    return rows


def summary(rows: list[dict[str, Any]]) -> dict[str, Any]:
    badges = [r.get("badges") or 0 for r in rows]
    costs = [r["cost"] for r in rows if isinstance(r.get("cost"), (int, float))]
    turns = sum(r.get("turns") or 0 for r in rows)
    fallbacks = sum(r.get("fallbacks") or 0 for r in rows)
    return {
        "runs": len(rows),
        "badges_mean": round(statistics.mean(badges), 3) if badges else 0,
        "badges_sem": round(statistics.stdev(badges) / len(badges) ** 0.5, 3)
        if len(badges) > 1 else 0,
        "badges_best": max(badges) if badges else 0,
        "completed": sum(r.get("ending") == "win-screen" for r in rows),
        "tokens_in": sum(r.get("tokens_in") or 0 for r in rows),
        "tokens_out": sum(r.get("tokens_out") or 0 for r in rows),
        "cached_tokens": sum(r.get("cached_tokens") or 0 for r in rows),
        "cache_write_tokens": sum(r.get("cache_write_tokens") or 0 for r in rows),
        "reasoning_tokens": sum(r.get("reasoning_tokens") or 0 for r in rows),
        "cost": round(sum(costs), 8) if rows and len(costs) == len(rows) else None,
        "cost_mean": round(statistics.mean(costs), 8)
        if rows and len(costs) == len(rows) else None,
        "cost_observed_runs": len(costs),
        "fallback_rate": round(fallbacks / turns, 3) if turns else 0,
    }


def run_model(bot_name: str, model: str, seeds: list[int], workers: int,
              endpoint: str | None, token: str | None, site: Path,
              port: int, max_steps: int = 400,
              on_progress: Callable[[list[dict[str, Any]]], None] | None = None) -> dict[str, Any]:
    workers = max(1, min(workers, len(seeds)))
    chunks = [seeds[i::workers] for i in range(workers)]
    context = mp.get_context("spawn")
    with TemporaryDirectory(prefix="pokelike-llm-bench-") as temp:
        temp_dir = Path(temp)
        result_paths = [temp_dir / f"worker-{i}.jsonl" for i in range(workers)]
        error_paths = [temp_dir / f"worker-{i}.error" for i in range(workers)]
        processes = [
            context.Process(
                target=_worker,
                args=(bot_name, model, chunk, endpoint, token, port + i,
                      str(site), max_steps, str(result_paths[i]), str(error_paths[i])),
            )
            for i, chunk in enumerate(chunks)
        ]
        for process in processes:
            process.start()

        try:
            reported = 0
            while any(process.is_alive() for process in processes):
                rows = _read_worker_rows(result_paths)
                if len(rows) > reported:
                    reported = len(rows)
                    if on_progress:
                        on_progress(rows)
                for i, process in enumerate(processes):
                    if process.exitcode not in (None, 0):
                        detail = (error_paths[i].read_text(encoding="utf-8").strip()
                                  if error_paths[i].is_file() else "unknown worker error")
                        raise RuntimeError(f"worker {i} failed: {detail}")
                time.sleep(0.25)

            for process in processes:
                process.join()
            rows = _read_worker_rows(result_paths)
            if len(rows) > reported and on_progress:
                on_progress(rows)
            if len(rows) != len(seeds):
                raise RuntimeError(f"benchmark produced {len(rows)}/{len(seeds)} results")
        finally:
            for process in processes:
                if process.is_alive():
                    process.terminate()
            for process in processes:
                process.join()
    rows.sort(key=lambda r: r["seed"])
    return {
        "model": model,
        "bot": bot_name,
        "harness": "cartographer-v1",
        "recorded_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "fingerprint": fingerprint(bot_name),
        "seeds": seeds,
        "summary": summary(rows),
        "runs": rows,
    }


def save(result: dict[str, Any]) -> Path:
    path = OUT / "results" / f"{slug(result['model'])}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(result, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


def recorded_results() -> list[dict[str, Any]]:
    results = []
    for path in sorted((OUT / "results").glob("*.json")):
        try:
            results.append(json.loads(path.read_text(encoding="utf-8")))
        except (OSError, json.JSONDecodeError):
            continue
    return results


def format_table(results: list[dict[str, Any]] | None = None) -> str:
    results = recorded_results() if results is None else results
    results.sort(
        key=lambda result: (
            -(result.get("summary") or {}).get("badges_mean", 0),
            result.get("model", ""),
        )
    )
    if not results:
        return "_No models measured yet._"
    lines = [
        "| # | model | runs | badges~ | ±sem | best | tok in/run | tok out/run | cached/run | fallback | $ | $/run |",
        "|--:|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|",
    ]
    for rank, result in enumerate(results, 1):
        s = result.get("summary") or {}
        runs = s.get("runs") or 0
        per_run = lambda key: round((s.get(key) or 0) / runs) if runs else 0
        total_cost = s.get("cost")
        mean_cost = s.get("cost_mean")
        lines.append(
            f"| {rank} | `{result.get('model', '?')}` | {runs} | "
            f"**{s.get('badges_mean', 0)}** | {s.get('badges_sem', 0)} | "
            f"{s.get('badges_best', 0)} | {per_run('tokens_in')} | "
            f"{per_run('tokens_out')} | {per_run('cached_tokens')} | "
            f"{s.get('fallback_rate', 0)} | "
            f"{f'{total_cost:.4f}' if isinstance(total_cost, (int, float)) else 'n/a'} | "
            f"{f'{mean_cost:.6f}' if isinstance(mean_cost, (int, float)) else 'n/a'} |"
        )
    return "\n".join(lines)


def update_readme(table: str | None = None) -> Path:
    table = table or format_table()
    text = README.read_text(encoding="utf-8")
    if README_BEGIN not in text or README_END not in text:
        raise RuntimeError(f"standings markers missing from {README}")
    before, rest = text.split(README_BEGIN, 1)
    _, after = rest.split(README_END, 1)
    README.write_text(
        f"{before}{README_BEGIN}\n\n{table}\n\n{README_END}{after}",
        encoding="utf-8",
    )
    return README
